#!/usr/bin/env node
/** Configure a copied template. This writes only non-secret project settings. */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { ROOT, assertSlug, normalizeUrl } from "./project-config.mjs";

function optionsFromArgs(args) {
  const values = {};
  for (let index = 0; index < args.length; index += 2) {
    const key = args[index];
    const value = args[index + 1];
    if (!key?.startsWith("--") || value === undefined) {
      throw new Error(`Expected --name value, got ${args.slice(index).join(" ")}`);
    }
    values[key.slice(2)] = value;
  }
  return values;
}

function required(values, name) {
  const value = values[name]?.trim();
  if (!value) throw new Error(`Missing --${name}`);
  return value;
}

function jsString(value) {
  return JSON.stringify(value);
}

const values = optionsFromArgs(process.argv.slice(2));
const projectName = assertSlug(required(values, "project"), "project name");
const workerName = assertSlug(values.worker?.trim() || projectName, "worker name");
const databaseName = assertSlug(values.database?.trim() || projectName, "database name");
const siteUrl = normalizeUrl(required(values, "site-url"));
const customDomain = values.domain?.trim().toLowerCase() || null;
const displayName = required(values, "display-name");
const tagline = values.tagline?.trim() || "Let your brand travel";
const ownerName = values.owner?.trim() || "The maker";
const email = values.email?.trim() || "hello@example.com";
const xUrl = values.x?.trim() || "";

if (customDomain && !/^[a-z0-9.-]+$/i.test(customDomain)) {
  throw new Error("Custom domain must be a hostname, without https:// or paths.");
}

const config = {
  projectName,
  workerName,
  databaseName,
  siteUrl,
  customDomain,
};

const wrangler = {
  $schema: "node_modules/wrangler/config-schema.json",
  name: workerName,
  main: "worker/index.ts",
  compatibility_date: "2024-12-30",
  compatibility_flags: ["nodejs_compat", "nodejs_compat_populate_process_env"],
  workers_dev: !customDomain,
  ...(customDomain
    ? { routes: [{ pattern: customDomain, custom_domain: true }] }
    : {}),
  assets: {
    directory: "out",
    binding: "ASSETS",
    not_found_handling: "single-page-application",
  },
  triggers: { crons: ["*/5 * * * *"] },
};

const siteConfig = `/**\n * Public identity for this deployment.\n *\n * Generated by scripts/configure-template.mjs. It contains no secrets.\n */\nexport const siteConfig = {\n  name: ${jsString(displayName)},\n  tagline: ${jsString(tagline)},\n  siteUrl: ${jsString(siteUrl)},\n  owner: {\n    name: ${jsString(ownerName)},\n    email: ${jsString(email)},\n    xUrl: ${jsString(xUrl)},\n  },\n} as const;\n`;

const packagePath = resolve(ROOT, "package.json");
const packageJson = JSON.parse(readFileSync(packagePath, "utf8"));
packageJson.name = projectName;

writeFileSync(resolve(ROOT, "boilerplate.config.json"), `${JSON.stringify(config, null, 2)}\n`);
writeFileSync(resolve(ROOT, "wrangler.jsonc"), `${JSON.stringify(wrangler, null, 2)}\n`);
writeFileSync(resolve(ROOT, "src/lib/site-config.ts"), siteConfig);
writeFileSync(packagePath, `${JSON.stringify(packageJson, null, 2)}\n`);

console.log(`Configured ${displayName} (${workerName}) for ${siteUrl}`);
